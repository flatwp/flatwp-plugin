const ICON_OPTIONS = Object.keys(ICONS).map((key) => ({
  label: key.charAt(0).toUpperCase() + key.slice(1),
  value: key,
}));

export default function Edit({ attributes, setAttributes, context }) {
  const { icon, title, description } = attributes;
  const iconPosition = context['flatwp/featuresIconPosition'] || 'top';

  const blockProps = useBlockProps({
    className: 'flatwp-feature-item',
  });

  const renderContent = () => {
    if (iconPosition === 'inline') {
      return (
        <>
          <div className="flatwp-feature-item__header">
            <div className="flatwp-feature-item__icon-wrapper">
              {ICONS[icon] || ICONS.star}
            </div>
            <RichText
              tagName="h3"
              className="flatwp-feature-item__title"
              value={title}
              onChange={(value) => setAttributes({ title: value })}
              placeholder={__('Feature title', 'flatwp')}
            />
          </div>
          <RichText
            tagName="p"
            className="flatwp-feature-item__description"
            value={description}
            onChange={(value) => setAttributes({ description: value })}
            placeholder={__('Feature description...', 'flatwp')}
          />
        </>
      );
    }

    return (
      <>
        <div className="flatwp-feature-item__icon-wrapper">
          {ICONS[icon] || ICONS.star}
        </div>
        <div className="flatwp-feature-item__content">
          <RichText
            tagName="h3"
            className="flatwp-feature-item__title"
            value={title}
            onChange={(value) => setAttributes({ title: value })}
            placeholder={__('Feature title', 'flatwp')}
          />
          <RichText
            tagName="p"
            className="flatwp-feature-item__description"
            value={description}
            onChange={(value) => setAttributes({ description: value })}
            placeholder={__('Feature description...', 'flatwp')}
          />
        </div>
      </>
    );
  };

  return (
    <>
      <InspectorControls>
        <PanelBody title={__('Feature Settings', 'flatwp')}>
          <SelectControl
            label={__('Icon', 'flatwp')}
            value={icon}
            options={ICON_OPTIONS}
            onChange={(value) => setAttributes({ icon: value })}
          />
        </PanelBody>
      </InspectorControls>

      <div {...blockProps}>{renderContent()}</div>
    </>
  );
}
